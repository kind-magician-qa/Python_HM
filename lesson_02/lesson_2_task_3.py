import math


def square(side):
    """
    Вычисляет площадь квадрата.
    Параметры:
        side (float или int): длина стороны квадрата.
    Возвращает:
        int: площадь квадрата, округлённая вверх, если результат не целый.
    """
    area = side * side
    # Округляем вверх, если площадь не целая (math.ceil всегда округляет вверх)
    return math.ceil(area)


# Вызов функции
print(square(5.8))
