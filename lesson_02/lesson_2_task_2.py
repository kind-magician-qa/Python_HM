def is_year_leap(year: int) -> bool:
    """
    Возвращает True, если год високосный, иначе False.
    По условию задачи: високосный год — тот, который делится на 4 без остатка.
    """
    return 0 == year % 4


# Ввод года
year = 2023
# Вызов функции и сохранение результата
result = is_year_leap(year)
# Вывод результата в требуемом формате
print(f"год {year}: {result}")
